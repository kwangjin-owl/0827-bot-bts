# ================================================================
#                        turn 이 무엇인가
# ================================================================
#
#  turn = 주고받기 한 번 = 내가 친 말 1개 + 봇이 한 답 1개.
#
#  app.py 의 chat(message, history) 가 받는 history 는 이렇게 생겼습니다.
#
#      history = [
#          ("쇼핑을 하려는데 서울 서쪽에 있을까요?", "...노량진 수산물 도매시장이 있습니다."),
#          ("오 네 거기 주소 좀 알려주세요.",        "...서울 동작구 93806입니다."),
#      ]
#
#  괄호 한 쌍이 turn 1개입니다.  len(history) 가 지금까지의 turn 수입니다.
#
#      history  = 지나간 turn 들     (내 말 + 봇 답이 짝지어 저장됨)
#      message  = 방금 친 말 하나     (아직 봇이 답을 안 했으니 짝이 없음)
#
#  HISTORY_TURNS 는 그 짝을 뒤에서 몇 개 볼지 정합니다.
#
#      recent = history[-HISTORY_TURNS:]
#
#  범위 밖으로 나간 turn 에서 말한 칸은 봇에게 안 넘어갑니다.
#  화면에는 그대로 보이는데 봇은 못 봅니다.  이것이 "범위 밖으로 밀림" 입니다.
#
#  WoS 원본 데이터는 이 문제가 없습니다.  turn 3 의 state 를 보면
#
#      ["관광-종류-쇼핑", "관광-지역-서울 서쪽", "관광-이름-노량진 수산물 도매시장"]
#
#  turn 1 에서 나온 것이 turn 3 에도 그대로 있습니다.  사람은 앞말을 기억하니까요.
#  WoS 의 state 가 정답지이고, 내 봇의 "채운 칸" 이 내 답안입니다.
#
# ----------------------------------------------------------------
#  주의 - "넘긴 것: N개" 는 turn 수가 아닙니다
# ----------------------------------------------------------------
#
#      turn 1개  ->  메시지 2개 (user 1 + model 1)
#      넘긴 것 = HISTORY_TURNS x 2 + 1     (마지막 +1 이 방금 친 말)
#
#  홀수만 나오는 이유가 이것입니다.
# ================================================================


# ----------------------------------------------------------------
#  1. 앞 대화를 몇 turn 까지 건넬까요?
#
#     이 값은 2 로 고정입니다.  바꾸지 않습니다.
#     2 = 바로 앞 두 번의 주고받기만 건넨다
#
#     이 제약 아래에서 아래 7칸을 다 받아내는 것이 오늘 과제입니다.
# ----------------------------------------------------------------
HISTORY_TURNS = 2


# ----------------------------------------------------------------
#  2. 어떻게 물어볼까요?
#
#     "one_by_one"  = 한 번에 한 칸씩 묻습니다
#     "all_at_once" = 필요한 것을 한 번에 다 묻습니다
#
#     칸이 7개라 one_by_one 이면 최소 7 turn 이 듭니다.
#     HISTORY_TURNS = 2 이므로 1~5번째 칸은 봇 시야에서 사라집니다.
#     즉 one_by_one 으로는 사실상 완성이 안 됩니다.
#
#     그래서 기본값을 all_at_once 로 둡니다.
#     둘 다 돌려 보고 무엇이 어떻게 달라지는지 적는 것이 과제의 절반입니다.
# ----------------------------------------------------------------
ASK_STYLE = "all_at_once"


# ----------------------------------------------------------------
#  3. 유저에게 물어서 채우는 칸
#
#     (칸 이름, 물어볼 말) 을 한 줄씩 적습니다.
#     줄을 지우면 봇이 그 칸을 묻지 않고, 웹에서도 그 입력칸이 사라집니다.
#
#     칸 이름에 도메인을 붙인 이유
#       관광에도 "종류" 가 있고 택시에도 "종류" 가 있습니다.
#       이름이 겹치면 모델이 뽑아낸 JSON 에서 한쪽이 다른 쪽을 덮어씁니다.
#       그래서 "장소 종류" / "택시 종류" 로 갈라 둡니다.
#
#     WoS 슬롯 목록 (참고)
#       식당    지역 / 종류 / 가격대 / 예약 시간 / 예약 명수      (5칸)
#       숙소    종류 / 가격대 / 숙박 기간 / 인터넷 / 주차          (5칸)
#       관광    종류 / 지역 / 이름                                (3칸)
#       택시    출발지 / 도착지 / 출발 시간 / 종류                 (4칸)
#       지하철  출발역 / 도착역                                   (2칸)
#
#     아래는 관광 3칸 + 택시 4칸 = 7칸입니다.
# ----------------------------------------------------------------
ASK_SLOTS = [
    ("장소 종류",   "어떤 곳을 찾으세요? 랜드마크, 박물관, 공원, 동물원, 쇼핑 중에서요."),
    ("장소 지역",   "서울 어느 쪽으로 찾아드릴까요? 중앙, 북쪽, 남쪽, 동쪽, 서쪽이 있어요."),
    ("장소 이름",   "가고 싶은 곳 이름이 정해져 있나요?"),
    ("택시 출발지", "택시를 어디서 타실 건가요?"),
    ("택시 도착지", "어디서 내리실 건가요?"),
    ("출발 시간",   "몇 시에 출발하실까요?"),
    ("택시 종류",   "택시 종류를 골라 주세요. 고급, 에코, 개인, 상관없음 중에서요."),
]


